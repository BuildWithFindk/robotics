<?php

/**
 * LogWriter.php — Markdown Log Formatter & Writer
 *
 * Takes a LogEntry and writes files. Knows nothing about git.
 */
class LogWriter
{
    private array $config;

    public function __construct(array $config)
    {
        $this->config = $config;
    }

    /** Write the full daily log at logs/YYYY-MM-DD.md (overwritten every run). */
    public function writeDailyLog(string $path, LogEntry $entry): void
    {
        $this->ensureDirectory(dirname($path));

        $commitSection = $this->formatCommitList($entry->commits);
        $net           = ($entry->netLines() >= 0 ? '+' : '') . $entry->netLines();
        $repoUrl       = 'https://github.com/' . $this->config['repository'];

        // PHP 7.3+ heredoc: the closing marker's indentation is stripped
        // from every line automatically.
        $md = <<<MD
            # 📋 Dev Log — {$entry->date}

            > **Project:** {$entry->projectName}
            > **Branch:** `{$entry->branch}`
            > **Author:** {$this->config['github_username']}
            > **Generated:** {$entry->timestamp}

            ---

            ## 📊 Daily Stats (since midnight)

            | Metric | Value |
            |--------|-------|
            | 📅 Day                 | {$entry->dayOfWeek} |
            | 🔀 Branch              | `{$entry->branch}` |
            | 💾 Commits Today       | {$entry->commitCount()} |
            | 📁 Files Changed       | {$entry->filesChanged} |
            | ➕ Lines Added         | +{$entry->insertions} |
            | ➖ Lines Removed       | -{$entry->deletions} |
            | 📈 Net Change          | {$net} lines |
            | 👤 Top Contributor     | {$entry->topContributor} |
            | 📦 Total Tracked Files | {$entry->totalFiles} |
            | ⚡ Activity Level      | {$entry->activityLevel()} |

            ---

            ## 🔧 Commits

            {$commitSection}

            ---

            *Auto-generated by [auto-commit-logger]({$repoUrl}) · {$entry->timestamp}*
            MD;

        file_put_contents($path, $md . "\n");
    }

    /**
     * Keep ONE row per date in CHANGELOG.md.
     *
     * The logger runs several times a day; each run replaces that date's
     * row with the latest numbers (the stats are cumulative for the day).
     * A new date is inserted right under the table header, newest first.
     */
    public function updateChangelog(string $path, LogEntry $entry): void
    {
        $row = sprintf(
            '| %s | %s | %d | %d | +%d / -%d | `%s` | %s |',
            $entry->date,
            $entry->dayOfWeek,
            $entry->commitCount(),
            $entry->filesChanged,
            $entry->insertions,
            $entry->deletions,
            $entry->branch,
            $entry->activityLevel()
        );

        if (!file_exists($path)) {
            $repoUrl = 'https://github.com/' . $this->config['repository'];

            $lines = [
                '# Changelog',
                '',
                "Auto-updated daily by [auto-commit-logger]({$repoUrl}).",
                '',
                '| Date | Day | Commits | Files | Lines | Branch | Activity |',
                '|------|-----|---------|-------|-------|--------|----------|',
                $row,
            ];

            file_put_contents($path, implode("\n", $lines) . "\n");
            return;
        }

        $lines   = explode("\n", rtrim(str_replace("\r\n", "\n", file_get_contents($path)), "\n"));
        $prefix  = '| ' . $entry->date . ' |';
        $divider = null;
        $found   = false;

        foreach ($lines as $i => $line) {
            if (str_starts_with($line, $prefix)) {
                $lines[$i] = $row;
                $found     = true;
                break;
            }
            if ($divider === null && preg_match('/^\|[-| ]+\|$/', $line)) {
                $divider = $i;
            }
        }

        if (!$found) {
            if ($divider === null) {
                $lines[] = $row;
            } else {
                array_splice($lines, $divider + 1, 0, [$row]);
            }
        }

        file_put_contents($path, implode("\n", $lines) . "\n");
    }

    // ── Private helpers ───────────────────────────────────────────────────────

    private function formatCommitList(array $commits): string
    {
        if (empty($commits)) {
            return '_No commits recorded today — rest is part of the process._';
        }

        $lines = [];
        foreach ($commits as $c) {
            $lines[] = "- `{$c['hash']}` **{$c['message']}** — _{$c['author']}_, {$c['time']}";
        }

        return implode("\n", $lines);
    }

    private function ensureDirectory(string $dir): void
    {
        if (!is_dir($dir)) {
            mkdir($dir, 0755, true);
        }
    }
}
